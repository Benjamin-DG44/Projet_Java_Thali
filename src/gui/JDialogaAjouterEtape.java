    /**
     * Insère une étape dns l'excursion actuelle
     * 
     * @param codeExcursion Identifiant de l'excursion actuelle
     * @param NumEtape Numéro de l'étape
     * @param Description Description de l'étape
     * @param DureePrevue Durée en (min) pour l'étape
     * @throws SQLException 
     */
    private void insertEtapeIntoDatabase(String codeExcursion, int NumEtape, String Description, int DureePrevue) throws SQLException {
        // Préparation de la requête SQL
        String sql = "INSERT INTO etape (CodeExcursion, NumEtape, Description, DureePrevue) VALUES (?, ?, ?, ?)";

        // Connexion à la base de données
        Connection connection = ConnexionBDD.getConnexion(); 
        PreparedStatement pstmt = connection.prepareStatement(sql);

        // On remplace chaque point d'interrogation par les informations correspodantes
        pstmt.setString(1, codeExcursion);
        pstmt.setInt(2, NumEtape);
        pstmt.setString(3, Description);
        pstmt.setDouble(4, DureePrevue);

        // Exécution de la requête
        pstmt.executeUpdate();
        JOptionPane.showMessageDialog(null, "Excursion ajoutée avec succès !");
       
    } 

