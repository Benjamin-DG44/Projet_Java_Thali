    private void jButtonAjouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAjouterActionPerformed
        // Récupère le contenu des cahmps de textes
    String NumEtape = jTextFieldNumEtape.getText(); 
    String Description = jTextFieldDescription.getText();
    String DureePrevue = jTextFieldDureePrevue.getText();
    
    // Vérifie si l'un des champs de texte est vide
    if (NumEtape.isEmpty() || Description.isEmpty() || DureePrevue.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Tous les champs doivent être remplis.");
        return; // Sortie de la méthode si des champs sont vides
    } 

    try {
        // Conversion des chaînes de caractères en types numériques
        int NumEtapeInt = Integer.parseInt(NumEtape);
        int DureePrevueInt = Integer.parseInt(DureePrevue);
        
        // Récupération du code d'excursion à partir de l'objet MiniExcursion
        String codeExcursion = excursionCourante.getCode(); // Utilise la variable d'instance

        // Insertion des données dans la base de données
        insertEtapeIntoDatabase(codeExcursion, NumEtapeInt, Description, DureePrevueInt);

        // Recharge la liste des excursions après l'ajout
        ((JFrameLesExcursions) getParent()).rechargerExcursions();
        this.dispose(); // Ferme la fenêtre actuelle
        
        // Vérifie que le nombre d'étape et la durée sont valides
        if (DureePrevueInt <= 0 || NumEtapeInt < 0) {
            JOptionPane.showMessageDialog(null, "Le nombre d'étape et la durée doivent être positifs.");
            return; // Sortie de la méthode si les valeurs ne sont pas valides
        }
    } catch (NumberFormatException e) {
        // Gestion des exceptions pour les conversions de type
        JOptionPane.showMessageDialog(null, "Veuillez entrer des valeurs numériques valides.");
        return; // Sortie de la méthode en cas d'erreur de format
    } catch (SQLException ex) {
        Logger.getLogger(JDialogaAjouterEtape.class.getName()).log(Level.SEVERE, null, ex);
    }
    
    this.dispose(); // Ferme la fenêtre
    }//GEN-LAST:event_jButtonAjouterActionPerformed

